// Package auth — токен-аутентификация клиента на узле.
//
// Токен предъявляется ВНУТРИ зашифрованного HTTP/3-запроса (в пути/заголовке,
// уже после TLS-хендшейка), поэтому невидим внешнему наблюдателю (DPI, firewall,
// NAT): снаружи — обычный HTTPS. Валидный токен → проксирование; невалидный или
// его отсутствие → отдаётся decoy-сайт. Токен НЕ пишется в заголовки IP/QUIC-
// пакетов, читаемые снаружи (требование по авторизации).
package auth

// Kind — роль предъявителя токена.
type Kind uint8

const (
	// User — обычный клиент.
	User Kind = iota
	// Node — сервисный токен узла: используется как chain-аутбаунд и в
	// скрипте-установщике при деплое новой ноды в сеть.
	Node
	// Admin — единый админ-токен: доступ к веб-панели управления любым узлом.
	Admin
)

// Token — проверенный секрет предъявителя.
type Token struct {
	Raw  string
	Kind Kind
}

// Authenticator проверяет сырой токен по хранилищу узла.
type Authenticator interface {
	// Verify возвращает Token и true, если секрет валиден; иначе false
	// (вызывающий отдаёт decoy).
	Verify(raw string) (Token, bool)
}
